"""Generate mid-asm hooks that log the game's calls to chosen kernel/XAM imports (arguments before, result after).

  python tools/py/gen_import_trace.py <generated_dir> <out.toml> <out.cpp> NAME [NAME ...]

Every call site `ctx.lr = 0xR; __imp__NAME(ctx, base);` in the generated code gets a hook at R-4 (r3..r7) and
one at R (r3 = the result). Bring-up only: add the .toml to the manifest's includes and the .cpp to the sources,
then remove both.
"""
import os
import re
import sys


def main():
    gen, out_toml, out_cpp, names = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    sites = {n: [] for n in names}
    pat = re.compile(r"ctx\.lr = 0x([0-9A-F]{8});\s*\n\s*__imp__(\w+)\(ctx, base\);")
    for f in sorted(os.listdir(gen)):
        if not f.endswith(".cpp"):
            continue
        for m in pat.finditer(open(os.path.join(gen, f), encoding="utf-8", errors="replace").read()):
            ret, name = int(m.group(1), 16), m.group(2)
            if name in sites:
                sites[name].append(ret)
    with open(out_toml, "w", newline="\n") as t:
        t.write("# Generated by tools/py/gen_import_trace.py (bring-up tracing, remove when done)\n")
        for name, rets in sites.items():
            for r in sorted(set(rets)):
                t.write(f'\n[[midasm_hook]]\nname = "Sc5Trace_{name}"\naddress = 0x{r - 4:08X}\n'
                        f'registers = ["r3", "r4", "r5", "r6", "r7"]\n')
                t.write(f'\n[[midasm_hook]]\nname = "Sc5TraceRet_{name}"\naddress = 0x{r:08X}\nregisters = ["r3"]\n')
    with open(out_cpp, "w", newline="\n") as c:
        c.write('// Generated by tools/py/gen_import_trace.py (bring-up tracing, remove when done)\n')
        c.write('#include <atomic>\n#include <cstdint>\n#include <rex/logging.h>\n#include <rex/ppc/context.h>\n\n')
        c.write('namespace {\nbool Want(std::atomic<uint32_t>& n) { const uint32_t k = ++n; return k <= 40 || k % 2000 == 0; }\n}\n\n')
        for name in names:
            c.write(f'static std::atomic<uint32_t> g_{name}{{0}}, g_ret_{name}{{0}};\n')
            c.write(f'void Sc5Trace_{name}(PPCRegister& r3, PPCRegister& r4, PPCRegister& r5, PPCRegister& r6, '
                    f'PPCRegister& r7) {{\n  if (Want(g_{name})) REXLOG_INFO("sc5 trace: {name}({{:08X}}, {{:08X}}, '
                    f'{{:08X}}, {{:08X}}, {{:08X}}) #{{}}", r3.u32, r4.u32, r5.u32, r6.u32, r7.u32, g_{name}.load());\n}}\n')
            c.write(f'void Sc5TraceRet_{name}(PPCRegister& r3) {{\n  if (Want(g_ret_{name})) '
                    f'REXLOG_INFO("sc5 trace: {name} -> {{:08X}}", r3.u32);\n}}\n\n')
    for name, rets in sites.items():
        print(f"{name}: {len(set(rets))} call sites")


if __name__ == "__main__":
    main()
