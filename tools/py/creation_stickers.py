"""The stickers Creation offers, for the check of created characters from another PC (sc5/src/sc5/creation_check.h):
python -I tools/py/creation_stickers.py <table.bin> > sc5/src/sc5/creation_stickers.inc

<table.bin> is the game's illustration table as Creation mode holds it in memory (CreationIllustrationInfo, 204-byte
entries; its schema: sub_8222AF20): uniqueID at +0, sortedIndex +4, ..., OLTIndex +16, OLTRelationIndex +17,
OLTKeyIndex +18 (the texture), releaseID +28. The online game never loads
it (it is Creation's), so the check carries the ids and their release ids, and asks the game at runtime which of those
releases this PC has (downloadable stickers only with their package)."""
import struct
import sys


def main():
    with open(sys.argv[1], "rb") as f:
        b = f.read()
    if len(b) % 204:
        raise SystemExit("not a table of 204-byte entries")
    rows = []
    for i in range(len(b) // 204):
        e = b[i * 204:(i + 1) * 204]
        uid = struct.unpack_from(">I", e, 0)[0]
        rel = struct.unpack_from(">I", e, 28)[0]
        # the texture it is (OLTIndex +16, OLTRelationIndex +17, OLTKeyIndex +18): a record's sticker repeats these
        rows.append((uid, rel, e[16], e[17], struct.unpack_from(">H", e, 18)[0]))
    rows.sort()
    if len({r[0] for r in rows}) != len(rows):
        raise SystemExit("ids repeat: not the illustration table")
    print("// The stickers Creation offers: {uniqueID, releaseID, OLTIndex, OLTRelationIndex, OLTKeyIndex} for each of")
    print("// the game's illustrations (CreationIllustrationInfo).")
    print(r"// Generated by tools\py\creation_stickers.py; do not edit.")
    line = ""
    for uid, rel, olt, olt_rel, olt_key in rows:
        item = f"{{0x{uid:05X}, 0x{rel:04X}, {olt}, {olt_rel}, {olt_key}}}, "
        if len(line) + len(item) > 118:
            print(line.rstrip())
            line = ""
        line += item
    if line:
        print(line.rstrip())


if __name__ == "__main__":
    main()
