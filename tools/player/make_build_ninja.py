#!/usr/bin/env python3
"""Writes games\\sc5\\build.ninja for the player package: every translated file compiled, and sc5game.dll linked, with
only what the package has (sc5/player/README.md). The list of translated files comes from this release's own codegen
(sc5/generated/default): the package carries its split of the functions into files, so every PC's codegen writes these.

Every path is relative to games\\sc5, so the folder a player unpacks into can have any name, and so is every path in
the depfiles that tell ninja what each file includes: clang's own headers are named relative too (-resource-dir), and
there is no precompiled header (whose users' depfiles name its headers by absolute path). Ninja cannot read an absolute
path with & in it from a depfile: it took the headers for missing and compiled everything again on every run. The
precompiled header saved under a tenth of each file's compile."""
import argparse
import pathlib
import re

parser = argparse.ArgumentParser()
parser.add_argument("--sources", required=True, help="sc5/generated/default/sources.cmake")
parser.add_argument("--clang-version", required=True, help="the folder of clang's headers in toolchain\\lib\\clang")
parser.add_argument("--out", required=True)
args = parser.parse_args()

CXXFLAGS = (
    "--target=x86_64-pc-windows-msvc -fms-compatibility-version=19.50 -march=$march -msse4.1 "
    "-O3 -DNDEBUG -std=gnu++23 -ffp-contract=off -fno-exceptions -fno-rtti -nostdlibinc "
    f"-resource-dir ../../toolchain/lib/clang/{args.clang_version} "
    "-DNOMINMAX -DREX_HAS_D3D12=1 -DWIN32_LEAN_AND_MEAN "
    "-Iplayer/include -Isdk/include -Isdk/include/simde"
)

names = re.findall(r"\$\{CMAKE_CURRENT_LIST_DIR\}/(\S+)\.cpp", pathlib.Path(args.sources).read_text(encoding="utf-8"))
names = [n for n in names if n != "sc5_register"]  # registers the code as a guest DLL: not used by one game
if len(names) < 2:
    raise SystemExit(f"no translated files listed in {args.sources}")

text = f"""# Compiles the game's translated code into sc5game.dll: see build-game.cmd. Generated by tools/player/make_build_ninja.py.
ninja_required_version = 1.10
builddir = build
include build/march.ninja
clang = ..\\..\\toolchain\\bin\\clang.exe
lld = ..\\..\\toolchain\\bin\\lld-link.exe
cxxflags = {CXXFLAGS}
gen = project/generated/default

rule cxx
  command = $clang $cxxflags -MD -MF $out.d -o $out -c $in
  depfile = $out.d
  deps = gcc
  description = Compiling $in

rule link
  command = $lld @$out.rsp
  rspfile = $out.rsp
  rspfile_content = /NOLOGO /DLL /NOENTRY /NODEFAULTLIB /MACHINE:X64 /OUT:$out $in @player/game_link.rsp /WHOLEARCHIVE:player/lib/sc5.lib sdk/lib/rexruntime.lib player/lib/msvcp140.lib player/lib/vcruntime140.lib player/lib/ucrtbase.lib
  description = Linking $out

build build/game_stub.obj: cxx player/game_stub.cpp
"""
objects = ["build/game_stub.obj"]
for n in names:
    text += f"build build/{n}.obj: cxx $gen/{n}.cpp\n"
    objects.append(f"build/{n}.obj")
text += ("build build/sc5game.dll: link " + " ".join(objects) +
         " | player/game_link.rsp player/lib/sc5.lib sdk/lib/rexruntime.lib\n")
text += "default build/sc5game.dll\n"
pathlib.Path(args.out).write_text(text, encoding="utf-8", newline="\n")
print(f"{args.out}: {len(names)} files")
